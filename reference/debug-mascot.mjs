import { chromium } from '@playwright/test';
const b = await chromium.launch({ channel: 'msedge' });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on('console', m => m.type() === 'error' && errs.push(m.text().slice(0, 200)));
p.on('pageerror', e => errs.push('PAGEERROR ' + e.message.slice(0, 200)));
await p.goto('http://localhost:3100/how-it-works', { waitUntil: 'networkidle' });
const m = p.getByRole('img', { name: /Biscuit, a curious caramel puppy/ });
console.log('count', await m.count());
const box = await m.boundingBox();
console.log('box', JSON.stringify(box));
const top = await p.evaluate(({ x, y }) => { const e = document.elementFromPoint(x, y); return e ? e.tagName + '.' + String(e.className?.baseVal ?? e.className).slice(0, 60) : null; }, { x: box.x + box.width / 2, y: box.y + box.height / 2 });
console.log('element at center:', top);
await p.mouse.move(box.x + box.width / 2 + 300, box.y + box.height / 2);
await p.mouse.move(box.x + box.width / 2 + 320, box.y + box.height / 2 + 4);
await p.waitForTimeout(400);
console.log('pupil transform', await m.locator('[data-p="pupil"]').first().evaluate(e => e.getAttribute('style')));
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2, { steps: 4 });
await p.waitForTimeout(300);
console.log('class after hover', await m.getAttribute('class'));
console.log('errors', errs);
await b.close();
