// Generates src/data/{puppies,families,gone-home}.ts from verified extraction (media.json + manifest).
import fs from 'node:fs';
import path from 'node:path';

const SP = process.argv[2];
const media = JSON.parse(fs.readFileSync(`${SP}/media.json`, 'utf8'));
const summary = JSON.parse(fs.readFileSync('reference/puppies-summary.json', 'utf8'));
const manifest = JSON.parse(fs.readFileSync('reference/asset-manifest.json', 'utf8'));
const local = u => '/images/' + (u.includes('/media/') ? (manifest.find(a => a.source.endsWith(u))?.group ?? 'puppies') : 'brand') + '/' + path.basename(u);
fs.mkdirSync('src/data', { recursive: true });

// catalogue order (from /puppies page)
const order = ['maltipoo-max-male', 'korean-teacup-maltipoo-female', 'korean-teacup-poodle-female', 'maltipoo-cavapoo-male', 'toy-poodle-male-female', 'maltipoo-female-2', 'pomeranian-female', 'copper-male', 'shitzu-female', 'shitzu-male', 'maltipoo-female-1', 'maltipoo-female', 'korean-teacup-pomeranian', 'korean-teacup-pomeranian-1', 'korean-teacup-pomeranian-male'];
const titles = {
  'maltipoo-max-male': ['Max', 'Maltipoo', ['maltipoo']],
  'korean-teacup-maltipoo-female': ['Korean Teacup Maltipoo', 'Korean Teacup Maltipoo', ['maltipoo', 'korean-teacup']],
  'korean-teacup-poodle-female': ['Korean Teacup Poodle', 'Korean Teacup Poodle', ['poodle', 'korean-teacup']],
  'maltipoo-cavapoo-male': ['Maltipoo & Cavapoo', 'Maltipoo & Cavapoo', ['maltipoo', 'cavapoo']],
  'toy-poodle-male-female': ['Toy Poodle', 'Toy Poodle', ['poodle']],
  'maltipoo-female-2': ['Maltipoo', 'Maltipoo', ['maltipoo']],
  'pomeranian-female': ['Pomeranian', 'Pomeranian', ['pomeranian']],
  'copper-male': ['Copper', 'Cavapoo', ['cavapoo']],
  'shitzu-female': ['Shih Tzu', 'Shih Tzu', ['shih-tzu']],
  'shitzu-male': ['Shih Tzu', 'Shih Tzu', ['shih-tzu']],
  'maltipoo-female-1': ['Maltipoo', 'Maltipoo', ['maltipoo']],
  'maltipoo-female': ['Maltipoo', 'Maltipoo', ['maltipoo']],
  'korean-teacup-pomeranian': ['Korean Teacup Pomeranian', 'Korean Teacup Pomeranian', ['pomeranian', 'korean-teacup']],
  'korean-teacup-pomeranian-1': ['Korean Teacup Pomeranian', 'Korean Teacup Pomeranian', ['pomeranian', 'korean-teacup']],
  'korean-teacup-pomeranian-male': ['Korean Teacup Pomeranian', 'Korean Teacup Pomeranian', ['pomeranian', 'korean-teacup']],
};

const puppies = order.map(slug => {
  const s = summary.find(x => x.slug === slug);
  const [name, breed, tags] = titles[slug];
  const raw = media['puppies__' + slug][0];
  const items = raw.map(m => m.kind === 'video'
    ? { kind: 'video', src: local(m.url), poster: local(m.poster.url), width: m.width, height: m.height, alt: m.alt }
    : { kind: 'image', src: local(m.url), width: m.width, height: m.height, alt: m.alt, color: m.color });
  const gender = s.gender === 'Boy' ? 'boy' : s.gender === 'Girl' ? 'girl' : 'boy & girl';
  return { slug, name, breed, tags, gender, age: s.age, origin: 'imported', media: items };
});
const head = '// Generated by reference/gen-data.mjs from the verified reference extraction. Edit with care.\n';
fs.writeFileSync('src/data/puppies.generated.ts', head + `import type { Puppy } from './types';\n\nexport const puppies: Puppy[] = ${JSON.stringify(puppies, null, 2)};\n`);

// families
const caps = ['Lulu 🧸 with her new mummy ❤️', 'Adorable Maltipoo baby 🧸❤️', 'My new teddy puppy 🥰🧸', 'Our new puppies 🧸🥰🤗', 'New puppy 🧸😍', 'Gang of 3 😍🧸', 'So happy 😍😍', 'New pup 🤗💫'];
const fam = media['happy-families'][0].map((m, i) => ({ id: m.id, src: local(m.url), width: m.width, height: m.height, alt: m.alt, color: m.color, caption: caps[i] ?? `Happy family ${i + 1}` }));
fs.writeFileSync('src/data/families.ts', head + `import type { FamilyPhoto } from './types';\n\nexport const families: FamilyPhoto[] = ${JSON.stringify(fam, null, 2)};\n`);

// gone home (names in page order; 27 images in the same order)
const names = [['Ace', 'Pomeranian', 'boy'], ['Leo', 'Poodle', 'boy'], ['Mia', 'Maltipoo', 'girl', 'Dubai showroom'], ['Sadie', 'Maltipoo', 'girl'], ['Pomeranian', 'Pomeranian', 'boy'], ['Ollie', 'Pomsky', 'boy'], ['Bruno', 'Maltipoo', 'boy'], ['Buddy', 'Maltese', 'boy'], ['Charlie', 'Maltese', 'boy'], ['Daisy', 'Pomeranian', 'girl'], ['Bella', 'Pomeranian', 'girl'], ['Teddy', 'Poodle', 'boy'], ['Molly', 'Poodle', 'girl'], ['Coco', 'Pomsky', 'girl'], ['Rosie', 'Pomsky', 'girl'], ['Leo', 'Pomeranian', 'boy'], ['Molly', 'Poodle', 'girl'], ['Rocky', 'Poodle', 'boy'], ['Sophie', 'Maltipoo', 'girl'], ['Lola', 'Maltipoo', 'girl'], ['Rex', 'Pomeranian', 'boy'], ['Finn', 'Pomsky', 'boy'], ['Zoe', 'Maltipoo', 'girl'], ['Mimi', 'Pomeranian', 'girl'], ['Bailey', 'Bichon', 'boy'], ['Maltipoo', 'Maltipoo', 'girl'], ['Poodle', 'Poodle', 'girl']];
const gh = manifest.filter(a => a.group === 'gone-home').sort((a, b) => a.index - b.index);
const gone = gh.map((a, i) => {
  const [name, breed, gender, note] = names[i] ?? ['Teddy Pup', 'Puppy', 'girl'];
  return { src: '/' + a.local.replace(/^public\//, ''), name, breed, gender, note: note ?? null };
});
fs.writeFileSync('src/data/gone-home.ts', head + `import type { GoneHomePup } from './types';\n\nexport const goneHome: GoneHomePup[] = ${JSON.stringify(gone, null, 2)};\n`);
